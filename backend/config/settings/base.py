def _warn_configuration_issue(message: str) -> None:
    warnings.warn(message, RuntimeWarning)


def _validate_database_configuration() -> None:
    default_db = DATABASES.get('default', {})
    engine = default_db.get('ENGINE', '')
    if engine in ('django.db.backends.postgresql', 'django.contrib.gis.db.backends.postgis'):
        missing = [field for field in ('NAME', 'USER', 'PASSWORD', 'HOST', 'PORT') if not default_db.get(field)]
        if missing:
            _warn_configuration_issue(
                'PostgreSQL database configuration is incomplete. Missing: ' + ', '.join(missing) + '. '
                'Set DATABASE_URL or individual database environment variables for production.',
            )
    elif engine == 'django.db.backends.sqlite3' and not DEBUG:
        _warn_configuration_issue(
            'SQLite is configured for production. Use PostgreSQL/PostGIS for production deployments.',
        )


def _validate_redis_configuration() -> None:
    if REDIS_URL:
        if not REDIS_URL.startswith(('redis://', 'rediss://')):
            _warn_configuration_issue(
                'REDIS_URL does not appear to be a valid Redis connection URL. Use redis:// or rediss://.',
            )
    elif not DEBUG and 'redis' in CELERY_BROKER_URL:
        _warn_configuration_issue(
            'Redis broker URL is not configured but Celery is set to use Redis. Set REDIS_URL or CELERY_BROKER_URL for production.',
        )


def _validate_storage_configuration() -> None:
    if STORAGE_BACKEND in ('s3', 'aws_s3', 'spaces', 'minio'):
        missing = [
            name for name in ('AWS_ACCESS_KEY_ID', 'AWS_SECRET_ACCESS_KEY', 'AWS_STORAGE_BUCKET_NAME')
            if not globals().get(name)
        ]
        if missing:
            _warn_configuration_issue(
                'S3-compatible storage configuration is incomplete. Missing: ' + ', '.join(missing) + '. '
                'Set the required AWS_* environment variables or select local storage for non-production usage.',
            )
        if STORAGE_BACKEND == 'minio' and not AWS_S3_ENDPOINT_URL:
            _warn_configuration_issue(
                'MinIO storage is configured but AWS_S3_ENDPOINT_URL is not set. Set AWS_S3_ENDPOINT_URL for MinIO.',
            )
    elif STORAGE_BACKEND == 'azure':
        missing = [
            name for name in ('AZURE_ACCOUNT_NAME', 'AZURE_ACCOUNT_KEY', 'AZURE_CONTAINER')
            if not globals().get(name)
        ]
        if missing:
            _warn_configuration_issue(
                'Azure Blob storage configuration is incomplete. Missing: ' + ', '.join(missing) + '. '
                'Set AZURE_ACCOUNT_NAME, AZURE_ACCOUNT_KEY, and AZURE_CONTAINER for production Azure storage.',
            )


def _validate_host_configuration() -> None:
    if not ALLOWED_HOSTS or ALLOWED_HOSTS == ['']:
        _warn_configuration_issue(
            'ALLOWED_HOSTS is empty. Set ALLOWED_HOSTS to the fully qualified hostnames for production.',
        )
    if not DEBUG and '*' in ALLOWED_HOSTS:
        _warn_configuration_issue(
            'Using ALLOWED_HOSTS="*" is permitted but not recommended in production. Restrict allowed hosts when possible.',
        )


def _validate_secret_key() -> None:
    if not SECRET_KEY or SECRET_KEY.startswith('django-insecure-') or len(SECRET_KEY) < 50 or len(set(SECRET_KEY)) < 5:
        _warn_configuration_issue(
            'SECRET_KEY is not secure. Provide a long, unique SECRET_KEY value in production.',
        )


def _validate_proxy_headers() -> None:
    if not DEBUG and USE_X_FORWARDED_HOST and not SECURE_PROXY_SSL_HEADER:
        _warn_configuration_issue(
            'USE_X_FORWARDED_HOST is enabled but SECURE_PROXY_SSL_HEADER is not configured. '
            'Set DJANGO_SECURE_PROXY_SSL_HEADER=True to correctly support reverse proxy HTTPS headers.',
        )


def _validate_runtime_configuration() -> None:
    if DEBUG:
        return

    _validate_secret_key()
    _validate_host_configuration()
    _validate_database_configuration()
    _validate_redis_configuration()
    _validate_storage_configuration()
    _validate_proxy_headers()


_validate_runtime_configuration()

